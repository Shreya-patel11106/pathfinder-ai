import React, { useState } from 'react';
import { 
  CheckCircle2, 
  Sparkles, 
  Download, 
  Share2, 
  Filter, 
  Clock, 
  Award, 
  BookOpen, 
  ArrowLeft,
  RefreshCw,
  Copy,
  Check
} from 'lucide-react';
import { CareerPath, Milestone, StudentProfile } from '../types';
import { MilestoneItem } from './MilestoneItem';
import roadmapVisual from '../assets/images/career_roadmap_illustration_1792777865247.jpg';

interface RoadmapViewProps {
  career: CareerPath;
  onToggleMilestone: (milestoneId: string) => void;
  onUpdateMilestoneNotes: (milestoneId: string, notes: string) => void;
  onAskAIAboutMilestone: (milestone: Milestone) => void;
  onBackToExplore: () => void;
  studentProfile: StudentProfile | null;
  onRegenerateCustomRoadmap: () => void;
  isRegenerating: boolean;
}

export const RoadmapView: React.FC<RoadmapViewProps> = ({
  career,
  onToggleMilestone,
  onUpdateMilestoneNotes,
  onAskAIAboutMilestone,
  onBackToExplore,
  studentProfile,
  onRegenerateCustomRoadmap,
  isRegenerating,
}) => {
  const [selectedPhaseFilter, setSelectedPhaseFilter] = useState<number | 'all' | 'incomplete'>('all');
  const [copiedExport, setCopiedExport] = useState(false);

  // Flatten milestones for stats
  const allMilestones: Milestone[] = career.roadmap.flatMap((phase) => phase.milestones);
  const completedCount = allMilestones.filter((m) => m.completed).length;
  const totalCount = allMilestones.length;
  const progressPercent = totalCount > 0 ? Math.round((completedCount / totalCount) * 100) : 0;

  const totalHours = allMilestones.reduce((acc, m) => acc + (m.estimatedHours || 0), 0);
  const completedHours = allMilestones
    .filter((m) => m.completed)
    .reduce((acc, m) => acc + (m.estimatedHours || 0), 0);

  // Filter logic
  const filteredPhases = career.roadmap.map((phase) => {
    let milestones = phase.milestones;
    if (selectedPhaseFilter === 'incomplete') {
      milestones = milestones.filter((m) => !m.completed);
    } else if (typeof selectedPhaseFilter === 'number') {
      milestones = phase.phaseNumber === selectedPhaseFilter ? milestones : [];
    }
    return {
      ...phase,
      milestones,
    };
  }).filter((phase) => phase.milestones.length > 0);

  // Export roadmap as clean Markdown
  const handleExportMarkdown = () => {
    let md = `# ${career.title} - Personalized Learning Roadmap\n`;
    md += `*Generated by PathFinder AI for ${studentProfile?.name || 'College Student'}*\n`;
    md += `*Goal: ${studentProfile?.targetGoal || 'Internship / First Job'} | Progress: ${completedCount}/${totalCount} Milestones (${progressPercent}%)*\n\n`;
    md += `---\n\n`;

    career.roadmap.forEach((phase) => {
      md += `## ${phase.phaseTitle} (${phase.timeframe})\n`;
      md += `> ${phase.summary}\n\n`;
      phase.milestones.forEach((m) => {
        md += `### [${m.completed ? 'x' : ' '}] ${m.title} (~${m.estimatedHours} hrs)\n`;
        md += `${m.description}\n\n`;
        md += `**Skills:** ${m.skillsGained.join(', ')}\n\n`;
        md += `**Free Resources:**\n`;
        m.freeResources.forEach((res) => {
          md += `- [${res.title}](${res.url}) (${res.provider} - ${res.type})\n`;
        });
        if (m.practicalProject) {
          md += `\n**Hands-on Project:** ${m.practicalProject.title}\n`;
          md += `- Deliverable: ${m.practicalProject.deliverable}\n`;
        }
        if (m.notes) {
          md += `\n**Student Notes:**\n${m.notes}\n`;
        }
        md += `\n---\n\n`;
      });
    });

    // Copy to clipboard and trigger text download
    navigator.clipboard.writeText(md);
    setCopiedExport(true);
    setTimeout(() => setCopiedExport(false), 2500);

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${career.title.toLowerCase().replace(/\s+/g, '-')}-roadmap.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 py-8 space-y-8">
      {/* Top action bar: back, title, export */}
      <div className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-200 pb-5">
        <div>
          <button
            type="button"
            onClick={onBackToExplore}
            className="text-xs font-semibold text-slate-500 hover:text-indigo-600 flex items-center gap-1.5 transition-colors mb-2 cursor-pointer"
          >
            <ArrowLeft className="w-4 h-4" />
            <span>Switch Career Track</span>
          </button>
          <div className="flex items-center gap-2 text-xs text-slate-500 mb-1">
            <span>{career.category}</span>
            <span aria-hidden="true">·</span>
            <span className="font-mono tabular-nums text-indigo-700 font-semibold">{career.matchScore}% Student Match</span>
          </div>
          <h2 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
            {career.title} Roadmap
          </h2>
        </div>

        <div className="flex items-center gap-3">
          <button
            type="button"
            onClick={onRegenerateCustomRoadmap}
            disabled={isRegenerating}
            className="px-3.5 py-2 text-xs font-semibold text-slate-700 bg-white border border-slate-300 hover:bg-slate-50 rounded-lg transition-all flex items-center gap-1.5 disabled:opacity-50 shadow-2xs"
          >
            <RefreshCw className={`w-3.5 h-3.5 text-indigo-600 ${isRegenerating ? 'animate-spin' : ''}`} />
            <span>{isRegenerating ? 'Customizing...' : 'AI Customize for My Schedule'}</span>
          </button>

          <button
            type="button"
            onClick={handleExportMarkdown}
            className="px-4 py-2 text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-700 rounded-lg transition-all flex items-center gap-1.5 shadow-2xs active:scale-95"
          >
            {copiedExport ? <Check className="w-3.5 h-3.5" /> : <Download className="w-3.5 h-3.5" />}
            <span>{copiedExport ? 'Copied & Downloaded!' : 'Export Roadmap (MD)'}</span>
          </button>
        </div>
      </div>

      {/* Progress & Milestone Stat Card + Visual banner */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 bg-white rounded-2xl border border-slate-200 p-6 shadow-xs">
        <div className="lg:col-span-8 space-y-5">
          <div>
            <div className="flex items-center justify-between text-xs font-bold text-slate-800 mb-2">
              <span className="flex items-center gap-1.5">
                <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                <span>Overall Learning Progress</span>
              </span>
              <span className="font-mono text-indigo-700 tabular-nums">
                {progressPercent}% Completed
              </span>
            </div>

            {/* Visual Progress Bar */}
            <div className="w-full bg-slate-100 rounded-full h-3 overflow-hidden border border-slate-200">
              <div
                className="bg-gradient-to-r from-indigo-600 to-emerald-500 h-full rounded-full transition-all duration-500 ease-out"
                style={{ width: `${progressPercent}%` }}
              />
            </div>
          </div>

          {/* 3 Metric blocks */}
          <div className="grid grid-cols-3 gap-3">
            <div className="p-3 bg-slate-50 rounded-xl border border-slate-100">
              <div className="text-[11px] text-slate-500 mb-0.5">Milestones Done</div>
              <div className="text-lg font-bold text-slate-900 font-mono tabular-nums">
                {completedCount} <span className="text-xs text-slate-400 font-normal">/ {totalCount}</span>
              </div>
            </div>

            <div className="p-3 bg-slate-50 rounded-xl border border-slate-100">
              <div className="text-[11px] text-slate-500 mb-0.5">Study Hours Logged</div>
              <div className="text-lg font-bold text-slate-900 font-mono tabular-nums">
                {completedHours} <span className="text-xs text-slate-400 font-normal">/ {totalHours}h</span>
              </div>
            </div>

            <div className="p-3 bg-slate-50 rounded-xl border border-slate-100">
              <div className="text-[11px] text-slate-500 mb-0.5">Total Cost</div>
              <div className="text-lg font-bold text-emerald-700 font-mono">
                $0 <span className="text-xs text-emerald-600 font-normal">100% Free</span>
              </div>
            </div>
          </div>

          <p className="text-xs text-slate-600 leading-relaxed">
            {career.matchReason} Follow the sequential phases below to build genuine competence. Each milestone includes verified free courses and a portfolio project you can upload to GitHub.
          </p>
        </div>

        {/* Visual Roadmap Graphic */}
        <div className="lg:col-span-4 rounded-xl overflow-hidden border border-slate-200 bg-slate-50 relative group">
          <img
            src={roadmapVisual}
            alt="Isometric Career Roadmap Milestones and Graduation Goals"
            referrerPolicy="no-referrer"
            className="w-full h-44 sm:h-52 lg:h-full object-cover object-center group-hover:scale-102 transition-transform duration-500"
          />
          <div className="absolute inset-0 bg-gradient-to-t from-slate-950/70 via-transparent to-transparent flex items-end p-3.5 text-white">
            <div className="text-xs">
              <span className="font-bold">20-Week Career Mastery Path</span>
              <p className="text-[11px] text-slate-200">From fundamentals to landing your offer</p>
            </div>
          </div>
        </div>
      </div>

      {/* Filter Tabs */}
      <div className="flex flex-wrap items-center gap-1.5 p-1 bg-slate-100 rounded-xl border border-slate-200 text-xs">
        <button
          type="button"
          onClick={() => setSelectedPhaseFilter('all')}
          className={`px-3 py-1.5 font-medium rounded-lg transition-colors whitespace-nowrap cursor-pointer ${
            selectedPhaseFilter === 'all'
              ? 'bg-white text-slate-900 shadow-2xs font-semibold'
              : 'text-slate-600 hover:text-slate-900'
          }`}
        >
          All 4 Phases ({totalCount})
        </button>

        {[1, 2, 3, 4].map((phaseNum) => (
          <button
            key={phaseNum}
            type="button"
            onClick={() => setSelectedPhaseFilter(phaseNum)}
            className={`px-3 py-1.5 font-medium rounded-lg transition-colors whitespace-nowrap cursor-pointer ${
              selectedPhaseFilter === phaseNum
                ? 'bg-white text-slate-900 shadow-2xs font-semibold'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            Phase {phaseNum}
          </button>
        ))}

        <button
          type="button"
          onClick={() => setSelectedPhaseFilter('incomplete')}
          className={`px-3 py-1.5 font-medium rounded-lg transition-colors whitespace-nowrap cursor-pointer ml-auto ${
            selectedPhaseFilter === 'incomplete'
              ? 'bg-white text-indigo-700 shadow-2xs font-semibold'
              : 'text-slate-600 hover:text-slate-900'
          }`}
        >
          Remaining Only ({totalCount - completedCount})
        </button>
      </div>

      {/* Phases and Milestones List */}
      <div className="space-y-8">
        {filteredPhases.map((phase) => (
          <section key={phase.phaseNumber} className="space-y-3">
            <div className="flex flex-wrap items-baseline justify-between gap-2 border-b border-slate-200 pb-2">
              <div>
                <h3 className="text-lg font-bold text-slate-900">
                  {phase.phaseTitle}
                </h3>
                <p className="text-xs text-slate-500 mt-0.5">{phase.summary}</p>
              </div>
              <span className="text-xs font-mono font-semibold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded border border-indigo-100 whitespace-nowrap">
                {phase.timeframe}
              </span>
            </div>

            <div className="space-y-3 pt-1">
              {phase.milestones.map((milestone) => (
                <MilestoneItem
                  key={milestone.id}
                  milestone={milestone}
                  onToggleComplete={onToggleMilestone}
                  onUpdateNotes={onUpdateMilestoneNotes}
                  onAskAIAboutMilestone={onAskAIAboutMilestone}
                />
              ))}
            </div>
          </section>
        ))}
      </div>
    </div>
  );
};
