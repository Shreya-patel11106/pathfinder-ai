import express from 'express';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '10mb' }));

// Initialize GoogleGenAI server-side with telemetry header
const geminiApiKey = process.env.GEMINI_API_KEY;
let ai: GoogleGenAI | null = null;

if (geminiApiKey) {
  ai = new GoogleGenAI({
    apiKey: geminiApiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
}

// System instruction for the AI Career Mentor Agent
const CAREER_AGENT_SYSTEM_PROMPT = `You are "PathFinder", an encouraging, deeply knowledgeable, practical AI Career Guide Agent dedicated to college and university students.
Your mission is to guide students—regardless of their prior experience or financial background—into fulfilling, high-impact careers using 100% FREE learning resources.
Key Persona Guidelines:
1. Speak in warm, clear, beginner-friendly English. Avoid dense corporate jargon.
2. Be practical and action-oriented: give concrete steps (e.g. specific project ideas, exact search queries, interview templates).
3. Always emphasize 100% free courses, tutorials, and open-source tools (e.g., Harvard CS50, freeCodeCamp, MIT OpenCourseWare, Kaggle, MDN Web Docs, Coursera free audit).
4. Emphasize building real projects over just watching tutorials ("tutorial hell").
5. Motivate students who may suffer from imposter syndrome or feel behind their peers.`;

// API route: Check service status
app.get('/api/status', (req, res) => {
  res.json({
    status: 'online',
    hasGeminiKey: Boolean(geminiApiKey),
    model: 'gemini-3.8-flash',
  });
});

// API route: Personalized Career Assessment
app.post('/api/gemini/career-assess', async (req, res) => {
  try {
    const { studentProfile } = req.body;

    if (!studentProfile) {
      return res.status(400).json({ error: 'Student profile is required' });
    }

    if (!ai) {
      // Fallback response if no key is supplied
      return res.json({
        source: 'curated_fallback',
        message: 'Using verified educational career paths repository.',
        aiAnalysis: `Based on your profile as a ${studentProfile.collegeYear} studying ${studentProfile.major} interested in ${studentProfile.interests?.join(', ')}, we identified high-growth career tracks tailored to your goals.`,
      });
    }

    const prompt = `Analyze this college student's profile and recommend 3 ideal career paths:
Student Profile:
- Year: ${studentProfile.collegeYear}
- Major: ${studentProfile.major}
- Key Interests: ${studentProfile.interests?.join(', ') || 'General technology and design'}
- Preferred Work Style: ${studentProfile.preferredWorkStyle}
- Target Goal: ${studentProfile.targetGoal}
- Weekly Study Time: ${studentProfile.weeklyHours} hours/week

Provide:
1. A 2-sentence empathetic analysis of their unique strengths and why their background is an advantage.
2. For each of 3 distinct recommended career paths:
   - title
   - category (Software Engineering, Data & AI, Product & Design, Cloud & Cybersecurity, or Business & Growth)
   - matchScore (number 80 to 98)
   - matchReason (1 sentence on why it directly aligns with their interests)
   - tagline (1 punchy line)
   - salaryRange (realistic entry-level starting salary)
   - jobGrowth (e.g., "+24% faster than average")
   - typicalDay (1-2 sentences on daily student/junior tasks)
   - coreSkills (list of 5-6 core tools/skills)
   - freeToolsUsed (list of 4-5 free software/platforms)

Respond in JSON format with keys: "aiAnalysis" (string) and "recommendations" (array of career objects).`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        systemInstruction: CAREER_AGENT_SYSTEM_PROMPT,
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    res.json({
      source: 'gemini_ai',
      aiAnalysis: parsed.aiAnalysis || 'Here are tailored career paths generated by your AI Career Mentor.',
      recommendations: parsed.recommendations || [],
    });
  } catch (error: any) {
    console.error('Error in career-assess:', error);
    res.status(500).json({
      error: 'Failed to generate career assessment with AI',
      details: error.message,
    });
  }
});

// API route: Personalized Learning Roadmap Generator
app.post('/api/gemini/generate-roadmap', async (req, res) => {
  try {
    const { careerTitle, studentProfile } = req.body;

    if (!careerTitle) {
      return res.status(400).json({ error: 'Career title is required' });
    }

    if (!ai) {
      return res.json({
        source: 'curated_fallback',
        message: 'Using comprehensive verified milestone roadmap.',
      });
    }

    const prompt = `Create a custom 4-phase, 20-week learning roadmap for a college student pursuing: "${careerTitle}".
Student Context:
- College Year: ${studentProfile?.collegeYear || 'Undergraduate'}
- Major: ${studentProfile?.major || 'Undeclared'}
- Study Commitment: ${studentProfile?.weeklyHours || 10} hours/week

Rules:
1. Divide into 4 phases:
   - Phase 1: Foundations & Core Concepts (Weeks 1 - 4)
   - Phase 2: Practical Skills & Hands-On Tools (Weeks 5 - 10)
   - Phase 3: Real-World Portfolio Projects (Weeks 11 - 16)
   - Phase 4: Resume, Interview & Internship Readiness (Weeks 17 - 20)
2. Every milestone must have:
   - title
   - description (simple English)
   - estimatedHours
   - skillsGained (array of strings)
   - freeResources (array of objects with: title, provider (e.g., freeCodeCamp, Harvard CS50, Kaggle, MDN, MIT OCW), url, type ("Free Course"|"Interactive Tutorial"|"Documentation"|"Guided Project"), difficulty ("Beginner"|"Intermediate"|"Advanced"))
   - practicalProject (object with: title, description, deliverable)
   - interviewQuestion (1 realistic technical or behavioral interview question)

Output valid JSON matching this schema:
{
  "phases": [
    {
      "phaseNumber": 1,
      "phaseTitle": "string",
      "timeframe": "string",
      "summary": "string",
      "milestones": [ ... ]
    }
  ]
}`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        systemInstruction: CAREER_AGENT_SYSTEM_PROMPT,
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    res.json({
      source: 'gemini_ai',
      phases: parsed.phases || [],
    });
  } catch (error: any) {
    console.error('Error in generate-roadmap:', error);
    res.status(500).json({
      error: 'Failed to generate roadmap with AI',
      details: error.message,
    });
  }
});

// API route: Interactive AI Career Mentor Chat
app.post('/api/gemini/chat', async (req, res) => {
  try {
    const { message, history, studentProfile, currentCareer } = req.body;

    if (!message) {
      return res.status(400).json({ error: 'Message is required' });
    }

    if (!ai) {
      // Helpful fallback replies if Gemini key is not configured
      const lower = message.toLowerCase();
      let reply = "Hello! I am your AI Career Mentor. I'm here to help you navigate courses, build standout projects, prepare for internships, and polish your resume. Feel free to ask any specific question!";
      if (lower.includes('internship') || lower.includes('no experience')) {
        reply = "Getting your first internship with zero experience is completely doable! Recruiters don't expect 5 years of industry experience—they want proof of initiative. Build 2 complete, deployed projects with clean GitHub READMEs, list quantifiable achievements on your resume using the Google X-Y-Z formula, and connect with university alumni on LinkedIn.";
      } else if (lower.includes('resume')) {
        reply = "For your resume: Keep it to 1 clean page. Prioritize Education, Projects, and Technical Skills. For every project, specify the problem solved, tech stack used, and live demo link. Always use active bullet points!";
      } else if (lower.includes('free') || lower.includes('course')) {
        reply = "Never pay hundreds for bootcamps when starting out! Check out Harvard CS50, freeCodeCamp, The Odin Project, Kaggle Learn, and Coursera's 100% Free Financial Aid. All give you world-class instruction for free.";
      }

      return res.json({
        reply,
        suggestions: [
          'How do I land an internship with no experience?',
          'What project should I build for my portfolio?',
          'How do I prepare for technical interviews for free?'
        ]
      });
    }

    // Build context-aware prompt for the agent
    const contextPrompt = `Student Context:
- Year: ${studentProfile?.collegeYear || 'College Student'}
- Major: ${studentProfile?.major || 'Undergrad'}
- Target Career Focus: ${currentCareer?.title || 'Exploring'}
- Study Commitment: ${studentProfile?.weeklyHours || 10} hours/week

User Message: "${message}"

Respond concisely (2-4 paragraphs max), empathetically, and practically in simple English. Include 2-3 quick bullet points or action items. Also suggest 3 follow-up questions the student could ask.
Output JSON format:
{
  "reply": "your helpful markdown-formatted response string",
  "suggestions": ["question 1", "question 2", "question 3"]
}`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: contextPrompt,
      config: {
        systemInstruction: CAREER_AGENT_SYSTEM_PROMPT,
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    res.json({
      reply: parsed.reply || "I'm here to help you navigate your college career journey. What specific area would you like to explore?",
      suggestions: parsed.suggestions || [
        'How should I structure my tech resume?',
        'What are the best free resources for beginners?',
        'How do I stand out in college career fairs?'
      ],
    });
  } catch (error: any) {
    console.error('Error in chat:', error);
    res.status(500).json({
      error: 'Failed to process chat message',
      details: error.message,
    });
  }
});

// Serve frontend in development vs production
async function startServer() {
  if (process.env.NODE_ENV === 'production') {
    // Production: serve built static assets from dist
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  } else {
    // Development: mount Vite development middlewares
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`PathFinder AI Career Guide server running on http://0.0.0.0:${PORT}`);
  });
}

startServer();
